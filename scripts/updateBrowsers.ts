import fs from "node:fs";
import path from "node:path";
import browserslist from "browserslist";

// Pins the client's browserslist config to the versions the rolling query
// resolves to today. Lint and build results then only move when this is run,
// never because a date passed between two runs on the same commit.

const query = [
  "last 5 years",
  // Niche browser families we don't support. browserslist has no per-browser
  // rolling syntax, so a family caniuse adds later is included until it is
  // excluded here; check the resolved set with: npx browserslist.
  "not android > 0", // Android WebView
  "not and_qq > 0", // QQ Browser for Android
  "not and_uc > 0", // UC Browser for Android
  "not baidu > 0", // Baidu Browser
  "not kaios > 0", // KaiOS Browser
  "not opera > 0", // Desktop Opera (Opera Mobile stays included)
];

// Names for the generated file's comments; a family missing here is listed
// without one, so add it when the resolved set grows a family
const browserNames: Partial<Record<string, string>> = {
  and_chr: "Chrome for Android",
  and_ff: "Firefox for Android",
  chrome: "Chrome",
  edge: "Edge",
  firefox: "Firefox",
  ios_saf: "Safari on iOS",
  op_mob: "Opera Mobile",
  safari: "Safari",
  samsung: "Samsung Internet",
};

const file = path.join("client", ".browserslistrc");
// Local date, so the stamp matches the commit it lands in
const now = new Date();
const today = [
  now.getFullYear(),
  String(now.getMonth() + 1).padStart(2, "0"),
  String(now.getDate()).padStart(2, "0"),
].join("-");

const isRange = (version: string): boolean => {
  return version.includes("-");
};
const byName = (a: string, b: string): number => {
  return a.localeCompare(b);
};

const browsers = browserslist(query);

// The oldest version per family. browserslist lists each family newest first.
const oldest = new Map<string, string>();
for (const browser of browsers) {
  const [id, version] = browser.split(" ", 2);
  oldest.set(id, version);
}

interface Pin {
  id: string;
  floor: string;
  steppedDownFrom: string | undefined;
}

// The compat lint skips a family whose oldest version is a caniuse range like
// 15.2-15.3, so such a floor steps down to the version below when that one is
// discrete
const pin = (id: string, version: string): Pin => {
  if (!isRange(version)) {
    return { id, floor: version, steppedDownFrom: undefined };
  }
  const lowerEnd = version.split("-", 1)[0];
  const below = browserslist([`${id} < ${lowerEnd}`])
    .at(0)
    ?.split(" ", 2)[1];
  if (below === undefined || isRange(below)) {
    console.warn(
      `${id} ${version} is a caniuse range and so is the version below, the compat lint will not check ${id}`,
    );
    return { id, floor: lowerEnd, steppedDownFrom: undefined };
  }
  return { id, floor: below, steppedDownFrom: version };
};

const pins = [...oldest]
  .map(([id, version]) => pin(id, version))
  .toSorted((a, b) => byName(a.id, b.id));

const width = Math.max(...pins.map((p) => `${p.id} >= ${p.floor}`.length));
const entries = pins.map((p) => {
  const pinQuery = `${p.id} >= ${p.floor}`;
  const name = browserNames[p.id];
  if (name === undefined) {
    console.warn(`no browser name for ${p.id}, add one to the script`);
    return { pinQuery, line: pinQuery };
  }
  const note =
    p.steppedDownFrom === undefined
      ? ""
      : ` (stepped down from ${p.steppedDownFrom})`;
  return { pinQuery, line: `${pinQuery.padEnd(width)} # ${name}${note}` };
});
const queries = entries.map((entry) => entry.pinQuery);

const content = [
  `# Generated by yarn update-browsers on ${today}, do not edit by hand`,
  `# Oldest versions "${query[0]}" resolved to on that date, minus the niche`,
  "# families the script excludes. Run it again to move the window.",
  "",
  ...entries.map((entry) => entry.line),
  "",
].join("\n");

const widened = pins
  .filter((p) => p.steppedDownFrom !== undefined)
  .map((p) => `${p.id} ${p.floor}`);
const expected = [...browsers, ...widened].toSorted(byName);
const resolved = browserslist(queries).toSorted(byName);
if (JSON.stringify(resolved) === JSON.stringify(expected)) {
  const previous = fs.existsSync(file)
    ? fs
        .readFileSync(file, "utf8")
        .split("\n")
        .map((line) => line.split("#", 1)[0].trim())
        .filter((line) => line !== "")
    : [];
  for (const q of previous.filter((p) => !queries.includes(p))) {
    console.log(`dropped ${q}`);
  }
  for (const q of queries.filter((p) => !previous.includes(p))) {
    console.log(`added ${q}`);
  }
  fs.writeFileSync(file, content);
  console.log(`${pins.length} browser families pinned in ${file}`);
} else {
  console.error("The pinned versions do not resolve back to the query");
  process.exitCode = 1;
}
